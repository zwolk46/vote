"""make_data.py: builds the three CSV files in model/math/data/ from true sources.

Run from the repository root:  python3 model/math/make_data.py <scratch directory>
The scratch directory holds the fetched sources, which are not committed:
  ec2016.html                      https://www.archives.gov/electoral-college/2016 (curl -sSL, 2026-11-07)
  medsl_1976-2024-president.csv    MIT Election Data and Science Lab, doi:10.7910/DVN/42MVDX v10 (CC0)
The Economist table is read from research/decisiveness-models-v2.md, Appendix B (its copy of the README).
The committed CSVs carry each source and its sha256 in a header line."""
import re, csv, json, html, hashlib
import sys
SRC=sys.argv[1].rstrip('/')+'/'   # directory holding ec2016.html (NARA page) and medsl_1976-2024-president.csv
# 1. Economist 2016 backtest table, from the repository's copy (research/decisiveness-models-v2.md, Appendix B, 0 differences from the README)
t=open('research/decisiveness-models-v2.md',encoding='utf-8').read()
i=t.index('**2016** (52 rows)')
block=t[i:]
rows=[]
for line in block.splitlines()[1:]:
    m=re.match(r'^\| (\S+) \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \| ([\d.]+) \|',line)
    if m: rows.append(m.groups())
    elif rows and not line.startswith('|'): break
print('economist rows',len(rows))
with open('model/math/data/economist_2016_backtest.csv','w',newline='') as f:
    f.write('# Source: TheEconomist/us-potus-model README (commit b89e602, 2020-10-15), table "Predictions for each state" for 2016, as copied in research/decisiveness-models-v2.md Appendix B (diffed against the README: 0 differences). Columns per README.Rmd: mean = posterior mean of the Democratic two-party share; low/high = 2.5%/97.5% quantiles; prob = P(share > 0.5); se = (high - mean)/1.68 (not a standard deviation). Row "-" is the national popular vote. Licence: CC BY 4.0 for data generated by The Economist.\n')
    w=csv.writer(f); w.writerow(['state','mean','low','high','prob','se'])
    for r in rows: w.writerow(['NAT' if r[0]=='–' else r[0]]+list(r[1:]))
# 2. NARA 2016 electoral votes
h=open(SRC+'ec2016.html',encoding='utf-8',errors='replace').read()
sha=hashlib.sha256(open(SRC+'ec2016.html','rb').read()).hexdigest()
trs=re.findall(r'<tr[^>]*>(.*?)</tr>',h,flags=re.S)
ev={}
names={'Alabama':'AL','Alaska':'AK','Arizona':'AZ','Arkansas':'AR','California':'CA','Colorado':'CO','Connecticut':'CT','Delaware':'DE','District of Columbia':'DC','Florida':'FL','Georgia':'GA','Hawaii':'HI','Idaho':'ID','Illinois':'IL','Indiana':'IN','Iowa':'IA','Kansas':'KS','Kentucky':'KY','Louisiana':'LA','Maine':'ME','Maryland':'MD','Massachusetts':'MA','Michigan':'MI','Minnesota':'MN','Mississippi':'MS','Missouri':'MO','Montana':'MT','Nebraska':'NE','Nevada':'NV','New Hampshire':'NH','New Jersey':'NJ','New Mexico':'NM','New York':'NY','North Carolina':'NC','North Dakota':'ND','Ohio':'OH','Oklahoma':'OK','Oregon':'OR','Pennsylvania':'PA','Rhode Island':'RI','South Carolina':'SC','South Dakota':'SD','Tennessee':'TN','Texas':'TX','Utah':'UT','Vermont':'VT','Virginia':'VA','Washington':'WA','West Virginia':'WV','Wisconsin':'WI','Wyoming':'WY'}
for r in trs:
    cells=[html.unescape(re.sub(r'<[^>]+>','',c)).strip() for c in re.findall(r'<t[dh][^>]*>(.*?)</t[dh]>',r,flags=re.S)]
    if len(cells)>=2:
        nm=cells[0].rstrip('*')
        if nm in names and cells[1].isdigit(): ev[names[nm]]=int(cells[1])
print('ev states',len(ev),'sum',sum(ev.values()))
with open('model/math/data/electoral_votes_2016.csv','w',newline='') as f:
    f.write('# Source: National Archives, https://www.archives.gov/electoral-college/2016 (fetched 2026-11-07 with curl; sha256 of the page %s), column "Number of Electoral Votes for Each State"; the 2010-census allocation in force for 2016. Total 538.\n'%sha)
    w=csv.writer(f); w.writerow(['state','ev'])
    for k in sorted(ev): w.writerow([k,ev[k]])
# 3. MEDSL 2016 state totals
rowsm=list(csv.DictReader(open(SRC+'medsl_1976-2024-president.csv',encoding='utf-8-sig')))
shm=hashlib.sha256(open(SRC+'medsl_1976-2024-president.csv','rb').read()).hexdigest()
st={}
for r in rowsm:
    if r['year']!='2016': continue
    k=r['state_po']; st.setdefault(k,{'total':int(r['totalvotes']),'dem':0,'rep':0})
    if r['party_simplified']=='DEMOCRAT': st[k]['dem']+=int(r['candidatevotes'])
    if r['party_simplified']=='REPUBLICAN': st[k]['rep']+=int(r['candidatevotes'])
with open('model/math/data/medsl_2016_state_totals.csv','w',newline='') as f:
    f.write('# Source: MIT Election Data and Science Lab, "U.S. President 1976-2024", Harvard Dataverse doi:10.7910/DVN/42MVDX, version 10, file 1976-2024-president.csv (datafile id 13887042, CC0 1.0; fetched 2026-11-07 by the documented API; sha256 %s). Derived here: for year 2016, totalvotes per state and the sums of candidatevotes with party_simplified DEMOCRAT and REPUBLICAN. MEDSL totals differ from the FEC in some states (research/decisiveness-models-v2.md, section 3.5).\n'%shm)
    w=csv.writer(f); w.writerow(['state','totalvotes','dem','rep'])
    for k in sorted(st): w.writerow([k,st[k]['total'],st[k]['dem'],st[k]['rep']])
print('medsl states',len(st), sum(v['total'] for v in st.values()))
