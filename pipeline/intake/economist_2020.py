"""Intake: The Economist's 2020 presidential forecast, final model output of 3 November 2020 (CC BY 4.0 data).

Written 2026-11-07 by worker D1 (briefs/D1-data-president.md; plan/PLAN.md section 3a).

Source: https://cdn.economistdatateam.com/us-2020-forecast/data/president/economist_model_output.zip, the
"Download model output" link on https://projects.economist.com/us-2020-forecast/president. Licence, from the
README inside the zip: "The data generated by The Economist are available under the Creative Commons
Attribution 4.0 International License" (the software under MIT); it "do[es] not cover any Economist content
or third-party data". The zip's timestamp.json is 1604404963 (2020-11-03 12:02 UTC).

What it writes: data/president/inputs/economist_2020.json:
  - topline: each state's projected Democratic share of the two-party vote on election day (mean, and the
    interval low and high, which equal the 2.5% and 97.5% points of the simulations, measured here) and
    its chance of winning, as published (state_averages_and_predictions_topline.csv, 2020-11-03);
  - the national summary (ec_summary.csv) and the correlation matrix of the simulated state shares
    (state_correlation_matrix.csv), as published;
  - p_decisive_vote by state (chance_casting_decisive_vote.csv), as published: "how likely a voter in that
    state is to tip the outcome of the election. Not used in the forecast" (the README). Kept as a check
    only (the brief), not shown as the site's p; its convention is unread (model section 4);
  - from the 80,000 joint simulations (electoral_college_simulations.csv, 30 MB, not committed), measured
    here: each state's mean and sd of the simulated share, and for the College stage the counts that
    pipeline/college.sims_window defines (draws within a window around one half, weighted by whether the
    state's electoral votes decide the College in that draw), for windows of 25, 50, 100 and 200 steps of
    0.0001 (the simulations print shares to four decimals).

Checks: 80,000 draws; 51 states; the published dem_ev of each draw equals the electoral votes of the states
over one half, except in draws where a state prints exactly 0.5 (rounding), which are counted; the topline
mean equals the simulations' mean within 0.0005.

Run from the repository root:  python3 pipeline/intake/economist_2020.py
"""
import csv
import io
import json
import os
import sys
import zipfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import college  # noqa: E402
import fetch  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "data", "president", "inputs", "economist_2020.json")
NARA = os.path.join(ROOT, "data", "president", "inputs", "nara_electoral_votes.json")
URL = "https://cdn.economistdatateam.com/us-2020-forecast/data/president/economist_model_output.zip"
NAME = "economist_2020_economist_model_output.zip"
PAGE = "https://projects.economist.com/us-2020-forecast/president"
STEP = 1e-4
WINDOWS = (25, 50, 100, 200)


def member(z, name):
    m = [n for n in z.namelist() if n.endswith("/" + name)]
    assert len(m) == 1, (name, m)
    return z.read(m[0]).decode("utf-8")


def main():
    path = fetch.fetch(URL, NAME)
    z = zipfile.ZipFile(path)                      # read in memory; nothing in it is run or unpacked to disk
    ts = json.loads(member(z, "timestamp.json"))["timestamp"]
    top = {r["state"]: r for r in csv.DictReader(io.StringIO(member(z, "state_averages_and_predictions_topline.csv")))}
    assert len(top) == 51 and {r["date"] for r in top.values()} == {"2020-11-03"}
    summary = list(csv.DictReader(io.StringIO(member(z, "ec_summary.csv"))))
    decisive = {r["state"]: float(r["p_decisive_vote"])
                for r in csv.DictReader(io.StringIO(member(z, "chance_casting_decisive_vote.csv")))}
    corr_rows = list(csv.reader(io.StringIO(member(z, "state_correlation_matrix.csv"))))
    corr_states = corr_rows[0][1:]
    corr = [[float(x) for x in r[1:]] for r in corr_rows[1:]]
    assert [r[0] for r in corr_rows[1:]] == corr_states and len(corr_states) == 51

    sims_text = member(z, "electoral_college_simulations.csv")
    rd = csv.reader(io.StringIO(sims_text))
    head = next(rd)
    states = head[3:]
    assert sorted(states) == sorted(top) == sorted(corr_states), "the files name different states"
    data = np.array([[float(x) for x in r] for r in rd])
    assert data.shape == (80000, 54), data.shape
    dem_ev = data[:, 1].astype(int)
    shares = data[:, 3:]
    ev_doc = json.load(open(NARA))["years"]["2020"]
    ev = np.array([ev_doc["states"][s]["ev"] for s in states])
    assert ev.sum() == 538
    won = shares > 0.5
    amb = np.isclose(shares, 0.5, atol=STEP / 10)
    recomputed = won @ ev
    mismatch = recomputed != dem_ev
    assert not (mismatch & ~amb.any(axis=1)).any(), "dem_ev differs from the states in a draw with no state at 0.5"
    print(f"80,000 draws; {int(mismatch.sum())} draws where a state printed at exactly 0.5 went to the Democrat "
          f"by the published dem_ev (rounding); none other")

    out_states = {}
    for i, s in enumerate(states):
        t = top[s]
        mean, sd = float(shares[:, i].mean()), float(shares[:, i].std())
        assert abs(mean - float(t["projected_vote_mean"])) < 5e-4, (s, mean, t["projected_vote_mean"])
        out_states[s] = {
            "ev": int(ev[i]),
            "published": {"mean": float(t["projected_vote_mean"]), "low": float(t["projected_vote_low"]),
                          "high": float(t["projected_vote_high"]), "win_prob": float(t["projected_win_prob"]),
                          "p_decisive_vote": decisive[s]},
            "sims": {"mean": mean, "sd": sd,
                     "q025": float(np.quantile(shares[:, i], 0.025)), "q975": float(np.quantile(shares[:, i], 0.975)),
                     "dem_share_draws": int((shares[:, i] > 0.5).sum()),
                     "windows": [college.sims_window(shares, dem_ev, ev, i, k, STEP, 538, 270) for k in WINDOWS]},
        }
        w = out_states[s]["sims"]["windows"][2]
        print(f"{s}: mean {mean:.4f} sd {sd:.4f}; window +-0.01: {w['in_window']} draws, weighted decisive"
              f" {w['weighted']:.1f}; published p_decisive_vote {decisive[s]:.3g}")
    m = fetch.meta(NAME)
    doc = {"about": "The Economist's final 2020 presidential forecast (model run of 2020-11-03), normalised by "
                    "pipeline/intake/economist_2020.py. Shares are the Democrat's share of the two-party vote.",
           "source": fetch.source("The Economist, 2020 US presidential forecast, model output "
                                  "(economist_model_output.zip)", URL, m["read_utc"],
                                  "CC BY 4.0 (data generated by The Economist; README in the zip)", "stated",
                                  note=f"linked from {PAGE} as 'Download model output'; zip timestamp {ts} "
                                       "(2020-11-03 12:02 UTC)", sha256=m["sha256"]),
           "model_date": "2020-11-03",
           "national": summary[-1] if summary else None,
           "correlation": {"states": corr_states, "matrix": corr},
           "draws": 80000, "window_step": STEP, "rounding_draws": int(mismatch.sum()),
           "states": out_states}
    with open(OUT, "w") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
